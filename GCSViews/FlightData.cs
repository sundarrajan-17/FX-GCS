        // Get Zoom and Target Coordinates from Gimbal and Camera Tracking Data
        public void GetFov(double zoom)
        {
            if (zoom < 1) zoom = 1;
            if (zoom > 30) zoom = 30;

            // Focal length
            double focal;
            if (zoom <= 20)
                focal = 4.4 + (zoom - 1.0) * (84.0 / 19.0);
            else
                focal = 88.4 * (zoom / 20.0);   // effective focal length for super-resolution

            const double sensorDiagonal = 7.18;
            const double sensorWidth  = sensorDiagonal * 4.0 / 5.0;  // 5.744 mm
            const double sensorHeight = sensorDiagonal * 3.0 / 5.0;  // 4.308 mm

            hfov = 2.0 * Math.Atan(sensorWidth / (2.0 * focal)) * 180.0 / Math.PI;
            vfov = 2.0 * Math.Atan(sensorHeight / (2.0 * focal)) * 180.0 / Math.PI;

            // return (hfov, vfov);
        }
        public void loadTargetLatLon(object sender,MAVLink.MAVLinkMessage packet)
        {
            switch (packet.msgid)
            {
                case (uint)MAVLink.MAVLINK_MSG_ID.CAMERA_FOV_STATUS:
                    var gimbaltrackdata = packet.ToStructure<MAVLink.mavlink_camera_fov_status_t>();
                    // target_latitude = gimbaltrackdata.lat_image * 1e-7;
                    // target_longitude = gimbaltrackdata.lon_image * 1e-7;
                    hfov = gimbaltrackdata.hfov;
                    vfov = gimbaltrackdata.vfov;
                    break; 
                case (uint)MAVLink.MAVLINK_MSG_ID.CAMERA_TRACKING_GEO_STATUS:
                    var gimbaltrackdata2 = packet.ToStructure<MAVLink.mavlink_camera_tracking_geo_status_t>();
                    target_latitude = gimbaltrackdata2.lat * 1e-7;
                    target_longitude = gimbaltrackdata2.lon * 1e-7;
                    break;
                case (uint)MAVLink.MAVLINK_MSG_ID.PARAM_VALUE:
                    var targetlatlonalt = packet.ToStructure<MAVLink.mavlink_param_value_t>();
                    Console.WriteLine("Param Value Data {0} {1}",targetlatlonalt.param_index,targetlatlonalt.param_value);
                    if(targetlatlonalt.param_index == 10)
                    {
                        target_longitude = targetlatlonalt.param_value;
                    }else if(targetlatlonalt.param_index == 11)
                    {
                        target_latitude = targetlatlonalt.param_value;
                    }else if(targetlatlonalt.param_index == 12)
                    {
                        target_altitude = targetlatlonalt.param_value;
                    }
                    break;
                case (uint)MAVLink.MAVLINK_MSG_ID.CAMERA_SETTINGS:
                    var camerasettings = packet.ToStructure<MAVLink.mavlink_camera_settings_t>();
                    Console.WriteLine("Camera Settings " + camerasettings.zoomLevel);
                    focal_length = 4.4*camerasettings.zoomLevel;
                    GetFov(camerasettings.zoomLevel);
                    break;
                case (uint)MAVLink.MAVLINK_MSG_ID.MOUNT_ORIENTATION:
                    var mountorientation = packet.ToStructure<MAVLink.mavlink_mount_orientation_t>();
                    cam_tilt = mountorientation.pitch;
                    cam_pan = mountorientation.yaw_absolute;
                    cam_roll = mountorientation.roll;
                    break;
                default:
                    break;
            }
        }

        public void Activate()
        {
            log.Info("Activate Called");

            OnResize(EventArgs.Empty);

            if (CB_tuning.Checked)
                ZedGraphTimer.Start();

            hud1.altunit = CurrentState.AltUnit;
            hud1.speedunit = CurrentState.SpeedUnit;
            hud1.distunit = CurrentState.DistanceUnit;
            coords1.AltUnit = CurrentState.AltUnit;

            if (MainV2.MONO)
            {
                if (!hud1.Visible)
                    hud1.Visible = true;
                if (!hud1.Enabled)
                    hud1.Enabled = true;

                hud1.Dock = DockStyle.Fill;
            }

            if (Settings.Instance.ContainsKey("quickViewRows"))
            {
                setQuickViewRowsCols(Settings.Instance["quickViewCols"], Settings.Instance["quickViewRows"]);
            }

            for (int f = 1; f < 30; f++)
            {
                // load settings
                if (Settings.Instance["quickView" + f] != null)
                {
                    Control[] ctls = Controls.Find("quickView" + f, true);
                    if (ctls.Length > 0)
                    {
                        QuickView QV = (QuickView) ctls[0];

                        // set description and unit
                        string desc = Settings.Instance["quickView" + f];
                        if (QV.Tag == null)
                            QV.Tag = desc;
                        QV.desc = MainV2.comPort.MAV.cs.GetNameandUnit(desc);

                        // set databinding for value
                        QV.DataBindings.Clear();
                        try
                        {
                            var b = new Binding("number", bindingSourceQuickTab,
                                Settings.Instance["quickView" + f], true);
                            b.Format += new ConvertEventHandler(BindingTypeToNumber);
                            b.Parse += new ConvertEventHandler(NumberToBindingType);

                            QV.DataBindings.Add(b);
                        }
                        catch (Exception ex)
                        {
                            log.Debug(ex);
                        }
                    }
                }
                else
                {
                    // if no config, update description on predefined
                    try
                    {
                        Control[] ctls = Controls.Find("quickView" + f, true);
                        if (ctls.Length > 0)
                        {
                            QuickView QV = (QuickView) ctls[0];
                            string desc = QV.desc;
                            if (QV.Tag == null)
                                QV.Tag = desc;
                            QV.desc = MainV2.comPort.MAV.cs.GetNameandUnit(QV.Tag.ToString());
                        }
                    }
                    catch (Exception ex)
                    {
                        log.Debug(ex);
                    }
                }
            }

            CheckBatteryShow();

            // make sure the hud user items/warnings/checklist are using the current state
            HUD.Custom.src = MainV2.comPort.MAV.cs;
            CustomWarning.defaultsrc = MainV2.comPort.MAV.cs;
            XagSurveillanceGCS.Controls.PreFlight.CheckListItem.defaultsrc = MainV2.comPort.MAV.cs;

            if (Settings.Instance["maplast_lat"] != "")
            {
                try
                {
                    gMapControl1.Position = new PointLatLng(Settings.Instance.GetDouble("maplast_lat"),
                        Settings.Instance.GetDouble("maplast_lng"));
                    if (Math.Round(Settings.Instance.GetDouble("maplast_lat"), 1) == 0)
                    {
                        // no zoom in
                        Zoomlevel.Value = 3;
                        TRK_zoom.Value = 3;
                    }
                    else
                    {
                        var zoom = Settings.Instance.GetFloat("maplast_zoom");
                        if (Zoomlevel.Maximum < (decimal) zoom)
                            zoom = (float) Zoomlevel.Maximum;
                        Zoomlevel.Value = (decimal) zoom;
                        TRK_zoom.Value = (float) Zoomlevel.Value;
                    }
                }
                catch
                {
                }
            }

            // update tabs displayed
            updateDisplayView();

            hud1.doResize();
        }

