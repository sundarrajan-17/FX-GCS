        private void quickView_DoubleClick(object sender, EventArgs e)
        {
            if (MainV2.DisplayConfiguration.lockQuickView)
                return;

            QuickView qv = (QuickView) sender;

            Form selectform = new Form
            {
                Name = "select",
                Width = MainV2.instance.Width - 100,
